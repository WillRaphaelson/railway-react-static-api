import assert from 'node:assert/strict';
const base = process.argv[2];
if (!base) throw new Error('Usage: node scripts/verify.mjs https://your-domain');
const home = await fetch(base);
assert.equal(home.status, 200);
const html = await home.text();
assert.match(html, /Fieldwork Studio/);
assert.equal((await fetch(new URL('/contact', base))).status, 200);
assert.equal((await fetch(new URL('/health', base))).status, 200);
const asset = html.match(/src="([^"]+\.js)"/)[1];
const js = await fetch(new URL(asset, base));
assert.equal(js.status, 200);
assert.match(js.headers.get('content-type'), /javascript/);
assert.match(js.headers.get('cache-control'), /immutable/);
assert.equal((await fetch(new URL('/assets/missing.js', base))).status, 404);
const send = payload => fetch(new URL('/api/contact', base), { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) });
const valid = await send({ name: 'Example Reader', email: 'reader@example.com', message: 'Testing the deployment example form submission.' });
assert.equal(valid.status, 200);
assert.match(valid.headers.get('cache-control'), /no-store/);
assert.equal((await valid.json()).ok, true);
assert.equal((await send({ email: 'invalid' })).status, 400);
assert.equal((await fetch(new URL('/api/missing', base))).status, 404);
console.log(JSON.stringify({ base, passed: ['home', 'nested route', 'health', 'asset content type', 'asset cache policy', 'missing asset 404', 'valid form', 'form no-store', 'invalid form 400', 'missing API 404'] }, null, 2));
